// Functions in JavaScript

function greet(name) {
    return `Hello, ${name}!`;
}
console.log(greet("Alice"));

const add = function(a, b) {
    return a + b;
};
console.log(add(5, 3));

const multiply = (a, b) => a * b;
console.log(multiply(4, 7));

const square = x => x * x;
console.log(square(5));

